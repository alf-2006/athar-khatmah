export function isMemorial(group) {
  return group?.kind === 'martyrs';
}

/** كل النصوص الظاهرة للمجلس بحسب نوعه. */
export function groupCopy(group) {
  const url = publicUrl(group.slug);
  const title = group.title;

  if (group.kind === 'martyrs') {
    return {
      verseTag: 'سجل الختمة القائمة',
      heading: 'خيرٌ يبقى وأثرٌ لا ينقطع',
      mobileHeading: 'مجلس أجزاء الختمة',
      desc: 'ختمة قرآنية جماعية مفتوحة، يقرأ فيها كل مشارك جزءه من مكانه وفي وقته بنية إهداء ثواب التلاوة والدعاء لشهداء حادث الحريق بالرحمة والمغفرة.',
      mobileSub: 'اختر جزءا متاحا لقراءته وإهداء ثوابه والدعاء لشهداء الحادث',
      prayers: MARTYRS_PRAYERS,
      footerLine: 'إنا لله وإنا إليه راجعون',
      docTitle: DEFAULT_TITLE,
      shareTitle: 'أثر | مجلس ختمة قرآنية جماعية',
      shareText: `مجلس ختمة قرآنية جماعية (أثر) بنية إهداء ثواب التلاوة والدعاء لشهداء الحادث بالرحمة والمغفرة:\n${url}`
    };
  }

  const deceased = group.kind.startsWith('deceased');
  const heading = deceased ? `عن روح ${title}` : title;
  const prayers = deceased
    ? [
        { heading: 'دعاء الجنازة المأثور', body: FORGIVENESS[group.kind] },
        { heading: 'دعاء إتمام التلاوة', body: COMPLETION[group.kind] }
      ]
    : GENERAL_PRAYERS;

  return {
    verseTag: 'مجلس ختمة · صدقة جارية',
    heading,
    mobileHeading: heading,
    desc: deceased
      ? `ختمة قرآنية جماعية مفتوحة صدقةً جارية عن روح ${title}. يقرأ كل مشارك جزءه من مكانه وفي وقته بنية إهداء ثواب التلاوة والدعاء بالرحمة والمغفرة.`
      : 'ختمة قرآنية جماعية مفتوحة صدقةً جارية، يقرأ فيها كل مشارك جزءه من مكانه وفي وقته بنية إهداء ثواب التلاوة.',
    mobileSub: deceased
      ? 'اختر جزءا متاحا لقراءته وإهداء ثوابه صدقة جارية'
      : 'اختر جزءا متاحا لقراءته وإهداء ثوابه',
    prayers,
    footerLine: deceased ? 'إنا لله وإنا إليه راجعون' : 'تقبل الله منا ومنكم',
    docTitle: deceased ? `ختمة عن روح ${title} | أثر` : `${title} | أثر`,
    shareTitle: deceased ? `ختمة عن روح ${title}` : title,
    shareText: deceased
      ? `ختمة قرآنية جماعية صدقة جارية عن روح ${title}. احجز جزءك واقرأه في وقتك وشاركنا الأجر:\n${url}`
      : `ختمة قرآنية جماعية صدقة جارية: ${title}. احجز جزءك واقرأه في وقتك وشاركنا الأجر:\n${url}`
  };
}

